/**
 * LooseLeaf UI - Design Token Build
 * Thin Node wrapper around scripts/tokens-core.mjs. Reads design-tokens.json and writes:
 *   - src/01-global/variables.css   custom properties (light, auto-dark, forced-dark)
 *   - dist/tokens.resolved.json     every token fully resolved (read by django-looseleaf)
 *   - docs/TOKENS.md                generated reference table
 *   - tools/current-tokens.js       classic-script copy of design-tokens.json (configurator Reset; file:// safe)
 */

const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");

const rootDir = path.join(__dirname, "..");
const tokenSourcePath = path.join(rootDir, "design-tokens.json");
const outputs = {
  css: path.join(rootDir, "src", "01-global", "variables.css"),
  resolved: path.join(rootDir, "dist", "tokens.resolved.json"),
  docs: path.join(rootDir, "docs", "TOKENS.md"),
  configurator: path.join(rootDir, "tools", "current-tokens.js"),
};

const TIER_NAMES = { 1: "Raw", 2: "Semantic", 3: "Component" };

function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, "utf8");
}

function markdownCell(value) {
  return value === undefined || value === null ? "" : String(value).replace(/\|/g, "\\|");
}

function renderMarkdown(tokens, report, target) {
  const lines = [
    "# Design Tokens",
    "",
    "> Generated by `npm run build:tokens` from `design-tokens.json`. Do not edit by hand.",
    "",
    "Tokens come in three tiers. **Raw** tokens (tier 1) are the palette and scales, derived from the",
    "`$palette` and `$utopia` inputs; blocks never use raw colours. **Semantic** tokens (tier 2) are named",
    "by purpose and are what blocks and compositions use; dark mode re-points them. **Component**",
    "tokens (tier 3) are declared inside each block with a semantic default.",
    "",
    "To change a derived value, change its input in `$palette` / `$utopia`. An explicit value in a",
    "derived group wins and is marked *overridden* below.",
    "",
    "## Breakpoint constant",
    "",
    "Custom properties cannot be used in container query conditions, so the single breakpoint is a",
    "documented constant: **`45rem`** (menu collapse). Use it only in `@container` rules.",
    "",
  ];

  if (report.length) {
    lines.push(
      "## Contrast",
      "",
      `WCAG 2.x ratios for the semantic text/surface pairings. Target: ${target}:1 (AA).`,
      "",
      "| Foreground | Background | Scheme | Ratio | AA |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const row of report) {
      lines.push(
        `| \`${row.foreground}\` | \`${row.background}\` | ${row.scheme} | ${row.ratio.toFixed(2)} | ${row.passes ? "pass" : "**fail**"} |`,
      );
    }
    lines.push("");
  }

  const groups = new Map();
  for (const token of tokens) {
    if (!groups.has(token.group)) groups.set(token.group, []);
    groups.get(token.group).push(token);
  }

  lines.push("## Tokens", "");
  for (const [group, groupTokens] of groups) {
    const purpose = groupTokens.find((token) => token.purpose)?.purpose;
    lines.push(`### ${group}`, "");
    if (purpose) lines.push(purpose, "");
    lines.push("| Token | Tier | Light | Dark | Notes |", "| --- | --- | --- | --- | --- |");
    for (const token of groupTokens) {
      const dark = token.themed ? `\`${markdownCell(token.dark)}\`` : "";
      const notes = token.overridden ? "overridden" : token.derived ? "derived" : "";
      lines.push(
        `| \`${token.name}\` | ${TIER_NAMES[token.tier] ?? token.tier} | \`${markdownCell(token.light)}\` | ${dark} | ${notes} |`,
      );
    }
    lines.push("");
  }

  return lines.join("\n");
}

async function main() {
  const { compile, contrastReport, resolvedTokens, CONTRAST_TARGET } = await import(
    pathToFileURL(path.join(__dirname, "tokens-core.mjs")).href
  );

  if (!fs.existsSync(tokenSourcePath)) {
    throw new Error(`Source file missing at: ${tokenSourcePath}`);
  }

  const json = JSON.parse(fs.readFileSync(tokenSourcePath, "utf8"));
  const { css, tokens } = compile(json);
  const report = contrastReport(tokens);

  write(outputs.css, css);
  // No $generated date here: rebuilding unchanged tokens must not produce a diff.
  const { version } = JSON.parse(fs.readFileSync(path.join(rootDir, "package.json"), "utf8"));
  write(outputs.resolved, JSON.stringify(resolvedTokens(tokens, { $version: version }), null, 2) + "\n");
  write(outputs.docs, renderMarkdown(tokens, report, CONTRAST_TARGET));
  write(
    outputs.configurator,
    `// AUTO-GENERATED by scripts/build-tokens.js from design-tokens.json. Do not edit.\nwindow.LooseLeafCurrentTokens = ${JSON.stringify(json, null, 2)};\n`,
  );

  for (const row of report.filter((r) => !r.passes)) {
    console.warn(
      `⚠️  Contrast ${row.ratio.toFixed(2)}:1 below ${CONTRAST_TARGET}:1 (${row.scheme}): ${row.foreground} ${row.fg} on ${row.background} ${row.bg}`,
    );
  }

  console.log(`✨ LooseLeaf UI compiled ${tokens.length} tokens to src/01-global/variables.css`);
}

main().catch((error) => {
  console.error(`❌ Token compilation failed: ${error.message}`);
  process.exit(1);
});
