/**
 * LooseLeaf UI - Configurator Library Build
 * Browsers refuse <script type="module"> from file:// (module scripts need CORS, and a
 * file page has a null origin), but classic scripts load fine. So the pure modules are
 * wrapped, unchanged apart from their import/export lines, into one classic script:
 * tools/tokens-lib.js, exposing window.LooseLeafTokens. The configurator then runs the
 * exact compiler the build runs, straight from a double-clicked HTML file.
 */

const fs = require("fs");
const path = require("path");

const rootDir = path.join(__dirname, "..");
const outputPath = path.join(rootDir, "tools", "tokens-lib.js");

// Dependency order: each module may only import from those before it.
const MODULES = ["utopia.mjs", "color.mjs", "spring.mjs", "tokens-core.mjs", "harmony.mjs", "solver.mjs", "zip.mjs"];

const importPattern = /^import\s*\{([^}]+)\}\s*from\s*"\.\/([\w.-]+\.mjs)";[ \t]*$/gm;
const exportPattern = /^export\s+((?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*))/gm;

function wrapModule(file, source, available) {
  const exported = [];

  let body = source.replace(importPattern, (_, names, dependency) => {
    if (!available.has(dependency)) {
      throw new Error(`${file} imports ${dependency}, which is not bundled before it`);
    }
    return `const {${names}} = modules["${dependency}"];`;
  });

  body = body.replace(exportPattern, (_, declaration, name) => {
    exported.push(name);
    return declaration;
  });

  const leftover = body.match(/^\s*(import|export)\b.*$/m);
  if (leftover) throw new Error(`Unsupported module syntax in ${file}: ${leftover[0].trim()}`);

  return `  modules["${file}"] = (() => {\n${body.trim()}\n\n  return { ${exported.join(", ")} };\n  })();`;
}

function bundle() {
  // The looseleaf-ui version, stamped into theme exports
  const { version } = JSON.parse(fs.readFileSync(path.join(rootDir, "package.json"), "utf8"));
  const available = new Set();
  const wrapped = MODULES.map((file) => {
    // Git may check sources out with CRLF or LF; the bundle is always LF.
    const source = fs.readFileSync(path.join(__dirname, file), "utf8").replace(/\r\n/g, "\n");
    const result = wrapModule(file, source, available);
    available.add(file);
    return result;
  });

  return `// AUTO-GENERATED by scripts/build-tools.js from ${MODULES.map((m) => `scripts/${m}`).join(", ")}. Do not edit.
(function (global) {
  "use strict";
  const modules = {};

${wrapped.join("\n\n")}

  global.LooseLeafTokens = Object.assign({ VERSION: ${JSON.stringify(version)} }, ${MODULES.map((m) => `modules["${m}"]`).join(", ")});
})(typeof window !== "undefined" ? window : globalThis);
`;
}

module.exports = { bundle };

if (require.main === module) {
  try {
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, bundle(), "utf8");
    console.log("✨ LooseLeaf UI configurator library bundled to tools/tokens-lib.js");
  } catch (error) {
    console.error(`❌ Configurator library build failed: ${error.message}`);
    process.exit(1);
  }
}
